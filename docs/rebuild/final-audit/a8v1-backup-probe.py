"""C14 verified-alternative retention after failed remote publication and corruption.

All DBs, encrypted archives, keys and restores are generated by the temporary fixture.
Remote is an in-process failure fake; no network or canonical data is involved.
"""
import pytest

from discordbot.operations.adapters.filesystem import read_json
from discordbot.platform.errors import DataIntegrityError
from tests.integration.operations.test_recovery import backup


@pytest.mark.asyncio
@pytest.mark.parametrize("orphan_count", [0, 7], ids=["verified-only-control", "corrupt-failed-publications"])
async def test_failed_corrupt_publications_do_not_displace_verified_backups(backup, tmp_path, orphan_count):
    verified = [await backup.create("synthetic-release") for _ in range(8)]
    # Prove every protected alternative is independently recoverable before fault.
    for index, identity in enumerate(verified):
        assert await backup.restore(tmp_path / f"verified-{index}.db", "synthetic-release",
                                    candidates=(identity,)) == identity

    class UnavailableRemote:
        async def publish(self, artifact, checksum, identity):
            raise OSError("synthetic remote failure")

    backup.remote = UnavailableRemote()
    invalid = []
    for _ in range(orphan_count):
        before = set(backup.root.glob("*.enc"))
        with pytest.raises(OSError, match="synthetic remote failure"):
            await backup.create("synthetic-release")
        created = set(backup.root.glob("*.enc")) - before
        assert len(created) == 1
        artifact = created.pop()
        artifact.write_bytes(b"synthetic corrupted orphan")
        invalid.append(artifact.stem)
        assert read_json(backup.root / "latest.json")["identity"] == verified[-1]
    # Failed operations have not pruned any valid archive yet.
    assert all((backup.root / (identity + ".enc")).exists() for identity in verified)
    for index, identity in enumerate(invalid):
        with pytest.raises(DataIntegrityError, match="no valid backup candidate"):
            await backup.restore(tmp_path / f"invalid-{index}.db", "synthetic-release",
                                 candidates=(identity,))

    backup.remote = None
    newest = await backup.create("synthetic-release")
    assert await backup.restore(tmp_path / "newest.db", "synthetic-release", candidates=(newest,)) == newest
    survivors = [identity for identity in verified if (backup.root / (identity + ".enc")).exists()]
    kept_invalid = [identity for identity in invalid if (backup.root / (identity + ".enc")).exists()]
    assert len(survivors) >= 7, (
        f"C14 requires eight verified alternatives: kept {len(survivors)} prior verified + 1 new; "
        f"kept {len(kept_invalid)} independently rejected corrupt publications instead"
    )
