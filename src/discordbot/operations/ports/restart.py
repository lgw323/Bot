"""Same-release restart under the caller-owned exclusive operation lock."""
from dataclasses import dataclass
from typing import Protocol

from discordbot.platform.errors import DataIntegrityError


class RestartCleanupUnconfirmed(DataIntegrityError):
    """Owned operations workers may still exist; no new evidence/start is safe."""


@dataclass(frozen=True, slots=True)
class RestartOutcome:
    result: str
    stage: str
    recovery: str = 'not_needed'
    recovery_stage: str = 'not_needed'
    healthy: bool = False
    audit_failed: bool = False


class RestartPort(Protocol):
    def preflight(self) -> None: ...
    def compatible(self) -> None: ...
    def checkpoint(self) -> object: ...
    def verify_checkpoint(self, proof: object) -> None: ...
    def stop(self) -> None: ...
    def quiescent(self) -> None: ...
    def stop_for_recovery(self) -> None: ...
    def start(self) -> None: ...
    def ready(self) -> None: ...
    def smoke(self) -> None: ...
    def audit(self, result: str, reason: str) -> None: ...
